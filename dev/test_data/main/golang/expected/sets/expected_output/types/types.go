// Check a local set in a method with a read-only set argument.
func (s *Something) OptionalTextsAreUniqueIgnoring(
	ignored map[string]struct{},
) bool {
	if s.OptionalTexts() == nil {
		return true
	}
	var seen map[string]struct{} = make(map[string]struct{})
	for _, text := range s.OptionalTexts() {
		if (
			ourcommon.MapContains(
				ignored,
				text,
			)) {
			continue
		}
		if (
			ourcommon.MapContains(
				seen,
				text,
			)) {
			return false
		}
		seen[text] = struct{}{}
	}
	return true
}

